export const IDS_IDIOMAS = IDIOMAS.map((i) => i.id);
export const idiomaValido = (v) => IDS_IDIOMAS.includes(v);
export const infoIdioma = (id) => IDIOMAS.find((i) => i.id === id) || IDIOMAS[0];

/** Idioma do aparelho do cliente → um dos seis (zh-TW também cai em chinês). */
export function detectarIdioma(preferidos = []) {
  for (const p of preferidos || []) {
    const base = String(p || "").toLowerCase().split("-")[0];
    if (idiomaValido(base)) return base;
  }
  return "pt";
}

